class DistVerificationError(RuntimeError):
    """Raised when a Lambda dist directory cannot be trusted."""


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _should_hash(path: Path) -> bool:
    return not (
        any(part in EXCLUDED_PARTS for part in path.parts)
        or path.suffix in EXCLUDED_SUFFIXES
        or path.name == ".DS_Store"
    )


def _ships(path: Path) -> bool:
    """Whether a distribution file goes into the archive and its tree hash.

    Source trees are hashed without bytecode, but the distribution carries the
    3.12 bytecode compiled for it, and nothing else from a cache directory, so
    bytecode some other interpreter happens to leave behind never changes the
    package.
    """
    if path.parent.name == "__pycache__" and path.name.endswith(BYTECODE_SUFFIX):
        return _should_hash(path.parent.parent)
    return _should_hash(path)


def sha256_tree(root: Path, relative_roots: tuple[str, ...]) -> str:
    digest = hashlib.sha256()
    for relative_root in relative_roots:
        base = root / relative_root
        if not base.exists():
            raise DistVerificationError(f"Missing source path: {relative_root}")
        for path in sorted(p for p in base.rglob("*") if p.is_file() and _should_hash(p)):
            relative = path.relative_to(root).as_posix()
            digest.update(relative.encode("utf-8"))
            digest.update(b"\0")
            digest.update(sha256_file(path).encode("ascii"))
            digest.update(b"\0")
    return digest.hexdigest()


def sha256_dist_tree(dist_dir: Path) -> str:
    """Hash every distribution file except the manifest that records the hash."""
    digest = hashlib.sha256()
    for path in sorted(dist_dir.rglob("*")):
        if path.is_symlink():
            raise DistVerificationError("Lambda dist contains a symlink")
        if not path.is_file() or path.name == MANIFEST_NAME or not _ships(path):
            continue
        relative = path.relative_to(dist_dir).as_posix()
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(sha256_file(path).encode("ascii"))
        digest.update(b"\0")
    return digest.hexdigest()


def git_output(root: Path, *args: str) -> str | None:
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return result.stdout.strip()


def git_sha(root: Path) -> str:
    return git_output(root, "rev-parse", "HEAD") or "unknown"


def git_dirty(root: Path) -> bool:
    status = git_output(root, "status", "--porcelain")
    return bool(status)


def handler_inventory(dist_dir: Path) -> dict[str, dict[str, Any]]:
    inventory: dict[str, dict[str, Any]] = {}
    for handler, relative_file in EXPECTED_HANDLERS.items():
        path = dist_dir / relative_file
        module_attr = handler.rsplit(".", 1)[1]
        exists = path.exists()
        has_attr = False
        if exists:
            source = path.read_text(encoding="utf-8", errors="replace")
            has_attr = f"{module_attr} =" in source or f"def {module_attr}(" in source
        inventory[handler] = {
            "file": relative_file,
            "exists": exists,
            "has_attr": has_attr,
        }
    return inventory


def require_handlers(dist_dir: Path) -> dict[str, dict[str, Any]]:
    inventory = handler_inventory(dist_dir)
    for handler, status in inventory.items():
        if status["exists"] is not True or status["has_attr"] is not True:
            raise DistVerificationError(f"{handler}: missing or invalid handler")
    return inventory


def export_locked_requirements(repo_root: Path) -> bytes:
    """Export runtime requirements from the committed lock without mutation."""
    command = [
        "uv",
        "export",
        "--format",
        "requirements-txt",
        "--no-dev",
        "--no-emit-project",
        "--locked",
    ]
    try:
        result = subprocess.run(
            command,
            cwd=repo_root,
            check=True,
            capture_output=True,
            env=_colourless_env(),
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        raise DistVerificationError("Fresh locked requirements export failed") from exc
    return SGR_SEQUENCE.sub(b"", result.stdout)


def _colourless_env() -> dict[str, str]:
    """Provenance must not depend on who launched the build. Observed under CDK
    synth, the exporter emitted ANSI-wrapped comment lines and the committed file
    looked drifted, so ask for uncoloured output. The caller also strips any
    escapes that survive, because the exporter decides this on its own terms."""
    env = {key: value for key, value in os.environ.items() if key not in COLOUR_FORCING_VARS}
    env["NO_COLOR"] = "1"
    return env


def verify_locked_requirements(repo_root: Path) -> bytes:
    requirements_path = repo_root / "requirements.txt"
    lock_path = repo_root / "uv.lock"
    if not requirements_path.is_file() or not lock_path.is_file():
        raise DistVerificationError("requirements.txt or uv.lock is missing")
    exported = export_locked_requirements(repo_root)
    committed_header, committed_payload = _requirements_payload(requirements_path.read_bytes())
    exported_header, exported_payload = _requirements_payload(exported)
    if committed_header != exported_header or committed_payload != exported_payload:
        raise DistVerificationError(
            "requirements.txt differs from the fresh locked export\n"
            + _requirements_drift(requirements_path.read_bytes(), exported)
        )
    return exported


def _requirements_drift(committed: bytes, exported: bytes, *, max_lines: int = 24) -> str:
    """Name the drift inline: this check runs inside CDK synth, where a bare
    'differs' message leaves no artifact to inspect afterwards."""
    diff = difflib.unified_diff(
        exported.decode("utf-8", "replace").splitlines(),
        committed.decode("utf-8", "replace").splitlines(),
        fromfile="fresh locked export",
        tofile="committed requirements.txt",
        lineterm="",
        n=1,
    )
    shown = list(itertools.islice(diff, max_lines + 1))
    if not shown:
        return "(no textual difference; the exporter emitted different bytes)"
    if len(shown) > max_lines:
        shown[max_lines] = f"... diff truncated at {max_lines} lines"
    return "\n".join(shown)


def _requirements_payload(value: bytes) -> tuple[bool, bytes]:
    lines = value.splitlines(keepends=True)
    if len(lines) >= 2 and lines[0] == UV_HEADER and lines[1] in UV_EXPORT_COMMANDS:
        return True, b"".join(lines[2:])
    return False, value


def current_python_version() -> str:
    return runtime_platform.python_version()


def host_runs_the_target() -> str | None:
    """Why this host cannot import the distribution, or None when it can.

    The distribution carries manylinux aarch64 binaries, so the smoke is a real
    check exactly where the host matches the runtime it was built for - which CI
    does, on `ubuntu-24.04-arm`. A developer's macOS cannot import those wheels
    at all, and the check used to fail there rather than report itself
    inapplicable. Since the same verification runs before every `cdk synth`, that
    made `cdk diff` impossible to run outside CI, and "look at the diff before
    deploying" was a step nobody could actually take.
    """
    system = runtime_platform.system()
    machine = runtime_platform.machine().lower()
    if system != "Linux":
        return f"host is {system}, and the distribution targets Linux"
    if machine not in {"aarch64", "arm64"}:
        return f"host is {machine}, and the distribution targets {ARCHITECTURE}"
    # A wrong interpreter version is not the same kind of fact. It is a host
    # somebody can fix, and skipping for it would hide a real mismatch, so it
    # stays an error below rather than a reason to stand down.
    return None


def foreign_binaries(dist_dir: Path) -> list[str]:
    """Compiled extensions in the distribution that this host cannot load.

    Judged from what is actually in the tree rather than from the host alone: a
    distribution with no compiled extension imports anywhere, and the smoke is a
    real check for it on any machine.
    """
    if not dist_dir.exists():
        return []
    machine = runtime_platform.machine().lower()
    host_linux = runtime_platform.system() == "Linux"
    host_arm = machine in {"aarch64", "arm64"}
    foreign: list[str] = []
    for binary in dist_dir.rglob("*.so"):
        name = binary.name.lower()
        if "linux" in name and not host_linux:
            foreign.append(binary.name)
        elif ("aarch64" in name or "arm64" in name) and not host_arm:
            foreign.append(binary.name)
    return sorted(foreign)


def boot_smoke(dist_dir: Path) -> dict[str, Any]:
    """Import the exact handlers through an isolated Python 3.12 process."""
    inapplicable = host_runs_the_target()
    unloadable = foreign_binaries(dist_dir)
    if inapplicable is not None and unloadable:
        return {
            "status": "SKIPPED",
            "reason": (
                f"{inapplicable}, and the distribution carries {len(unloadable)} "
                "extensions built for it; the smoke runs where the host matches, which CI does"
            ),
            "runtime_target": RUNTIME_TARGET,
        }
    if not current_python_version().startswith("3.12."):
        raise DistVerificationError("Lambda boot smoke requires Python 3.12")
    handler_pairs = [handler.rsplit(".", 1) for handler in sorted(EXPECTED_HANDLERS)]
    code = (
        "import importlib,json,sys;"
        "sys.path.insert(0,sys.argv[1]);"
        "pairs=json.loads(sys.argv[2]);"
        "assert all(callable(getattr(importlib.import_module(module), attr, None)) "
        "for module,attr in pairs)"
    )
    environment = dict(os.environ)
    for name in tuple(environment):
        if name.startswith("AWS_") or name in {
            "HTTP_PROXY",
            "HTTPS_PROXY",
            "ALL_PROXY",
            "http_proxy",
            "https_proxy",
            "all_proxy",
        }:
            environment.pop(name, None)
    environment["AWS_EC2_METADATA_DISABLED"] = "true"
    environment["PYTHONDONTWRITEBYTECODE"] = "1"
    try:
        subprocess.run(
            # -B, because -I ignores PYTHONDONTWRITEBYTECODE: the smoke must not
            # write bytecode into the tree it is checking.
            [sys.executable, "-I", "-B", "-c", code, str(dist_dir.resolve()), json.dumps(handler_pairs)],
            cwd=dist_dir,
            env=environment,
            check=True,
            capture_output=True,
            timeout=30,
        )
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
        raise DistVerificationError("Lambda handler boot smoke failed") from exc
    return {
        "runtime_target": RUNTIME_TARGET,
        "handler_count": len(handler_pairs),
        "status": "PASS",
    }


def cdk_asset_hash(manifest: dict[str, Any]) -> str:
    stable_fields = {key: value for key, value in manifest.items() if key != "cdk_asset_hash"}
    encoded = json.dumps(stable_fields, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def build_manifest(
    repo_root: Path,
    dist_dir: Path,
) -> dict[str, Any]:
    requirements_path = repo_root / "requirements.txt"
    pyproject_path = repo_root / "pyproject.toml"
    uv_lock_path = repo_root / "uv.lock"
    if not requirements_path.exists():
        raise DistVerificationError("Missing requirements.txt")
    if not pyproject_path.exists():
        raise DistVerificationError("Missing pyproject.toml")
    verify_locked_requirements(repo_root)

    inventory = require_handlers(dist_dir)
    manifest = {
        "schema_version": 1,
        "project": "stoa-backend",
        "source_git_sha": git_sha(repo_root),
        "source_git_dirty": git_dirty(repo_root),
        "source_tree_hash": sha256_tree(repo_root, HASHED_SOURCE_ROOTS),
        "distribution_tree_hash": sha256_dist_tree(dist_dir),
        "requirements_hash": sha256_file(requirements_path),
        "pyproject_hash": sha256_file(pyproject_path),
        "uv_lock_hash": sha256_file(uv_lock_path),
        "runtime_target": RUNTIME_TARGET,
        "python_version": PYTHON_VERSION,
        "platform": PLATFORM,
        "architecture": ARCHITECTURE,
        "expected_handlers": sorted(EXPECTED_HANDLERS),
        "handler_inventory": inventory,
        "boot_smoke": boot_smoke(dist_dir),
    }
    manifest["cdk_asset_hash"] = cdk_asset_hash(manifest)
    return manifest


def validate_manifest(repo_root: Path, dist_dir: Path) -> dict[str, Any]:
    manifest_path = dist_dir / MANIFEST_NAME
    if not manifest_path.exists():
        raise DistVerificationError(f"Missing Lambda dist manifest: {manifest_path}")

    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise DistVerificationError("Lambda dist manifest is malformed") from exc
    if not isinstance(manifest, dict):
        raise DistVerificationError("Lambda dist manifest is malformed")
    if set(manifest) != BUILD_MANIFEST_KEYS:
        raise DistVerificationError("Lambda dist manifest fields are not closed")
    expected_manifest = build_manifest(repo_root, dist_dir)
    expected = {
        key: value for key, value in expected_manifest.items() if key != "cdk_asset_hash"
    }
    errors: list[str] = []
    for key, expected_value in expected.items():
        actual_value = manifest.get(key)
        if actual_value != expected_value:
            errors.append(f"{key}: expected {expected_value!r}, found {actual_value!r}")

    inventory = manifest.get("handler_inventory") or {}
    current_inventory = handler_inventory(dist_dir)
    for handler, status in current_inventory.items():
        if not status["exists"]:
            errors.append(f"{handler}: missing dist file {status['file']}")
        if not status["has_attr"]:
            errors.append(f"{handler}: handler attribute missing in {status['file']}")
        recorded = inventory.get(handler) or {}
        if recorded.get("exists") is not True or recorded.get("has_attr") is not True:
            errors.append(f"{handler}: manifest does not record a valid handler")
    errors.extend(bytecode_problems(dist_dir))

    expected_asset_hash = cdk_asset_hash(manifest)
    if manifest.get("cdk_asset_hash") != expected_asset_hash:
        errors.append(
            "cdk_asset_hash: expected "
            f"{expected_asset_hash!r}, found {manifest.get('cdk_asset_hash')!r}"
        )

    if errors:
        joined = "\n  - ".join(errors)
        raise DistVerificationError(f"Lambda dist verification failed:\n  - {joined}")
    return manifest


def install_dependencies(repo_root: Path, dist_dir: Path) -> None:
    cmd = [
        sys.executable,
        "-m",
        "pip",
        "install",
    ]
    for compatible_platform in COMPATIBLE_PLATFORMS:
        cmd.extend(("--platform", compatible_platform))
    cmd.extend([
        "--implementation",
        "cp",
        "--python-version",
        PYTHON_VERSION,
        "--only-binary",
        ":all:",
        # compile_bytecode writes the bytecode the package ships; pip's own is
        # timestamp-based and would only be overwritten.
        "--no-compile",
        "--target",
        str(dist_dir),
        "-r",
        str(repo_root / "requirements.txt"),
    ])
    subprocess.run(cmd, cwd=repo_root, check=True)


def copy_source(repo_root: Path, dist_dir: Path) -> None:
    source = repo_root / "src" / "stoa"
    destination = dist_dir / "stoa"
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(source, destination, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo"))
    copy_security_inventory(repo_root, destination)


def copy_security_inventory(repo_root: Path, package_dir: Path) -> None:
    """Carry the sealed inventory into the bundle beside the code that reads it.

    Account deletion loads this before it does anything. Only `.py` files were
    ever packaged, so every deletion in production failed on a missing file and
    answered `identity_conflict` -- a message about identity, for a bundle that
    was missing a document.
    """
    target = package_dir / "security_inventory"
    target.mkdir(parents=True, exist_ok=True)
    for name in (SECURITY_INVENTORY_NAME, SECURITY_INVENTORY_V2_NAME):
        inventory = repo_root / "docs" / "security" / name
        if not inventory.is_file():
            if name == SECURITY_INVENTORY_V2_NAME:
                # Only the registry path needs it, and it is off without it.
                continue
            raise SystemExit(f"missing sealed inventory: {inventory}")
        shutil.copy2(inventory, target / name)


def compile_bytecode(dist_dir: Path) -> None:
    """Compile every module in the distribution for the Lambda runtime.

    `/var/task` is read-only, so a package without bytecode is compiled from
    source on every cold start and the result thrown away: about 1.3 s of the
    API's import (#341). Lambda only uses bytecode from the interpreter it runs,
    so any other is refused here.

    Hash-based and unchecked (PEP 552). The archive pins every timestamp to 1980,
    which would invalidate timestamp-based bytecode on arrival. And source cannot
    change under bytecode shipped beside it in one read-only package; re-reading
    every source file at import to prove that costs each cold start about 55 ms.
    bytecode_problems proves it once per build and verify instead.
    """
    if not current_python_version().startswith(f"{PYTHON_VERSION}."):
        raise DistVerificationError(
            f"Lambda bytecode must be compiled by Python {PYTHON_VERSION}, "
            f"not {current_python_version()}"
        )
    root = str(dist_dir.resolve())
    # No inherited PYTHON* setting may redirect or change the output
    # (PYTHONPYCACHEPREFIX, PYTHONOPTIMIZE); the hash seed is pinned so set
    # constants marshal in the same order in every build.
    environment = {key: value for key, value in os.environ.items() if not key.startswith("PYTHON")}
    environment["PYTHONHASHSEED"] = "0"
    command = [
        sys.executable,
        # Never import from the distribution itself while compiling it.
        "-P",
        "-m",
        "compileall",
        "-q",
        "-f",
        "-j",
        "0",
        "--invalidation-mode",
        "unchecked-hash",
        # Record each module at its Lambda path rather than this build's
        # directory, so builds in different places produce the same bytes.
        "-s",
        root,
        "-p",
        LAMBDA_TASK_ROOT,
        root,
    ]
    try:
        subprocess.run(command, env=environment, check=True, capture_output=True, text=True)
    except subprocess.CalledProcessError as exc:
        detail = "\n".join((exc.stdout or "").strip().splitlines()[-20:])
        raise DistVerificationError(f"Lambda bytecode compilation failed\n{detail}") from exc
    except OSError as exc:
        raise DistVerificationError("Lambda bytecode compilation failed") from exc
    problems = bytecode_problems(dist_dir)
    if problems:
        raise DistVerificationError("Lambda bytecode is incomplete:\n  - " + "\n  - ".join(problems))


def bytecode_problems(dist_dir: Path, *, max_reported: int = 10) -> list[str]:
    """Modules that do not ship the 3.12 bytecode of exactly their own source.

    Lambda never re-reads the source of unchecked bytecode, so a module changed
    after compiling would run its old code with nothing noticing. The source hash
    is keyed by the 3.12 magic number explicitly, which gives the runtime's
    answer from any interpreter, so `--verify-only` still works off the target.
    """
    key = int.from_bytes(BYTECODE_MAGIC, "little")
    problems: list[str] = []
    for source in sorted(dist_dir.rglob("*.py")):
        if not source.is_file() or not _ships(source):
            continue
        relative = source.relative_to(dist_dir).as_posix()
        compiled = source.parent / "__pycache__" / f"{source.stem}{BYTECODE_SUFFIX}"
        try:
            with compiled.open("rb") as handle:
                header = handle.read(16)
        except OSError:
            problems.append(f"{relative}: no {BYTECODE_SUFFIX} bytecode")
            continue
        if (
            header[:4] != BYTECODE_MAGIC
            or int.from_bytes(header[4:8], "little") != UNCHECKED_HASH_FLAGS
            or header[8:16] != _imp.source_hash(key, source.read_bytes())
        ):
            problems.append(f"{relative}: bytecode is not the unchecked-hash 3.12 build of this source")
    if len(problems) > max_reported:
        problems[max_reported:] = [f"... and {len(problems) - max_reported} more modules"]
    return problems


def write_manifest(repo_root: Path, dist_dir: Path) -> dict[str, Any]:
    manifest = build_manifest(repo_root, dist_dir)
    manifest_path = dist_dir / MANIFEST_NAME
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def build_dist(
    repo_root: Path,
    dist_dir: Path,
    *,
    skip_install: bool = False,
    skip_smoke: bool = False,
) -> dict[str, Any]:
    verify_locked_requirements(repo_root)
    if dist_dir.exists():
        shutil.rmtree(dist_dir)
    dist_dir.mkdir(parents=True)
    if not skip_install:
        install_dependencies(repo_root, dist_dir)
    copy_source(repo_root, dist_dir)
    # Last, so nothing changes a module after its bytecode is written.
    compile_bytecode(dist_dir)
    if skip_smoke:
        # Build the manifest with a SKIPPED smoke record.
        # Intended for cross-compilation builds on macOS where Linux ARM64
        # binaries cannot be imported. CI always runs on Linux and performs the real smoke test.
        import platform as _platform
        inventory = {h: str((repo_root / "src" / p).resolve()) for h, p in EXPECTED_HANDLERS.items()}
        manifest: dict[str, Any] = {
            "schema_version": 1,
            "project": "stoa-backend",
            "source_git_sha": git_sha(repo_root),
            "source_git_dirty": git_dirty(repo_root),
            "source_tree_hash": sha256_tree(repo_root, HASHED_SOURCE_ROOTS),
            "distribution_tree_hash": sha256_dist_tree(dist_dir),
            "requirements_hash": sha256_file(repo_root / "requirements.txt"),
            "pyproject_hash": sha256_file(repo_root / "pyproject.toml"),
            "uv_lock_hash": sha256_file(repo_root / "uv.lock"),
            "runtime_target": RUNTIME_TARGET,
            "python_version": PYTHON_VERSION,
            "platform": PLATFORM,
            "architecture": ARCHITECTURE,
            "expected_handlers": sorted(EXPECTED_HANDLERS),
            "handler_inventory": inventory,
            "boot_smoke": {
                "status": "SKIPPED",
                "reason": (
                    f"cross-compilation build on {_platform.system()} — "
                    "Linux ARM64 binaries cannot be imported on host; smoke runs in CI"
                ),
                "runtime_target": RUNTIME_TARGET,
            },
        }
        manifest["cdk_asset_hash"] = cdk_asset_hash(manifest)
        manifest_path = dist_dir / MANIFEST_NAME
        manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return manifest
    manifest = write_manifest(repo_root, dist_dir)
    validate_manifest(repo_root, dist_dir)
    return manifest


def zip_dist(dist_dir: Path, zip_path: Path) -> dict[str, Any]:
    if zip_path.exists():
        zip_path.unlink()
    paths: list[Path] = []
    for path in dist_dir.rglob("*"):
        if path.is_symlink():
            raise DistVerificationError("Lambda dist archive cannot contain a symlink")
        if path.is_file() and _ships(path):
            paths.append(path)
    # Order by the archive name validate_archive_identity checks. Sorting Path
    # objects compares parts, which disagrees with byte order wherever a package
    # directory sits beside a longer sibling: "pkg/mod.py" sorts before
    # "pkg-1.0.dist-info/RECORD" by parts but after it by bytes.
    paths.sort(key=lambda path: path.relative_to(dist_dir).as_posix())
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for path in paths:
            relative = path.relative_to(dist_dir).as_posix()
            info = zipfile.ZipInfo(relative, date_time=ZIP_TIMESTAMP)
            info.create_system = 3
            info.external_attr = (stat.S_IFREG | ZIP_FILE_MODE) << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(
                info,
                path.read_bytes(),
                compress_type=zipfile.ZIP_DEFLATED,
                compresslevel=9,
            )
    identity = {
        "bytes": zip_path.stat().st_size,
        "entry_count": len(paths),
        "sha256": sha256_file(zip_path),
    }
    validate_archive_identity(zip_path, identity)
    if identity["bytes"] > DIRECT_UPLOAD_LIMIT_BYTES:
        raise DistVerificationError(
            f"Lambda archive is {identity['bytes']} bytes; update-function-code --zip-file "
            f"accepts at most {DIRECT_UPLOAD_LIMIT_BYTES}. Upload it through S3 instead."
        )
    return identity


def validate_archive_identity(zip_path: Path, identity: dict[str, Any]) -> None:
    if set(identity) != {"bytes", "entry_count", "sha256"}:
        raise DistVerificationError("Lambda archive identity is not closed")
    if (
        not zip_path.is_file()
        or identity.get("bytes") != zip_path.stat().st_size
        or identity.get("sha256") != sha256_file(zip_path)
    ):
        raise DistVerificationError("Lambda archive digest or length mismatch")
    try:
        with zipfile.ZipFile(zip_path) as archive:
            infos = archive.infolist()
            if identity.get("entry_count") != len(infos):
                raise DistVerificationError("Lambda archive entry count mismatch")
            if [info.filename for info in infos] != sorted(info.filename for info in infos):
                raise DistVerificationError("Lambda archive order is not normalized")
            for info in infos:
                if (
                    info.date_time != ZIP_TIMESTAMP
                    or stat.S_IMODE(info.external_attr >> 16) != ZIP_FILE_MODE
                ):
                    raise DistVerificationError("Lambda archive metadata is not normalized")
            if archive.testzip() is not None:
                raise DistVerificationError("Lambda archive contains corrupt bytes")
    except (OSError, zipfile.BadZipFile) as exc:
        raise DistVerificationError("Lambda archive is malformed") from exc


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--dist", type=Path, default=None)
    parser.add_argument("--verify-only", action="store_true")
    parser.add_argument("--skip-install", action="store_true")
    parser.add_argument(
        "--skip-smoke",
        action="store_true",
        help="Skip the Lambda handler boot smoke test. Use on macOS cross-compilation "
             "builds where Linux ARM64 binaries cannot be imported. CI always runs smoke.",
    )
    parser.add_argument("--zip", type=Path, default=None, help="Optional zip path to create after build")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    repo_root = args.repo_root.resolve()
    dist_dir = (args.dist or repo_root / "dist").resolve()
    try:
        if args.verify_only:
            manifest = validate_manifest(repo_root, dist_dir)
            print(
                "Lambda dist verified: "
                f"sha={manifest['source_git_sha']} "
                f"source_tree_hash={manifest['source_tree_hash'][:12]}"
            )
            return 0
        manifest = build_dist(repo_root, dist_dir, skip_install=args.skip_install, skip_smoke=args.skip_smoke)
        if args.zip:
            zip_dist(dist_dir, args.zip.resolve())
        print(
            "Lambda dist built: "
            f"sha={manifest['source_git_sha']} "
            f"source_tree_hash={manifest['source_tree_hash'][:12]}"
        )
        return 0
    except DistVerificationError as exc:
        print(str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
